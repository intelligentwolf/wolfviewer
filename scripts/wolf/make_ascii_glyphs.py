#!/usr/bin/env python3
"""[WOLF ASCII 2026-10-24] Paul: "in photo effects can we add an ASCII ART mode? ... it should be drawn with actual ASCII
characters". Renders real ASCII glyphs from DejaVu Sans Mono Bold into 8x12 one-bit cells, measures each glyph's ink (the classic ramp, sorted by the ink measured here), and
prints the GLSL table for app_settings/shaders/class1/post/wolfPhotoFilterF.glsl (mode 16): WP_ASCII[] = 3 uints a glyph
(rows 0-3, 4-7, 8-11, 8 bits a row, bit 7 = leftmost pixel), ordered from least to most ink.
Usage: make_ascii_glyphs.py [font.ttf]"""
import sys
from PIL import Image, ImageDraw, ImageFont

FONT = sys.argv[1] if len(sys.argv) > 1 else "/usr/share/fonts/TTF/DejaVuSansMono-Bold.ttf"
W, H = 8, 12
RAMP = " .:-=+*#%@"   # the classic 10-step ASCII-art ramp (Paul Bourke, "Character representation of greyscale images")

def glyph(ch, font):
    im = Image.new("L", (W, H), 0)
    d = ImageDraw.Draw(im)
    l, t, r, b = d.textbbox((0, 0), ch, font=font)
    # drawn in the cell's top-left 7x11 so a full-width glyph ('+', '=') never touches its neighbour: the right
    # column and bottom row stay empty, the gap a terminal font leaves between characters
    d.text(((W - 1 - (r - l)) / 2 - l, (H - 1 - (b - t)) / 2 - t), ch, fill=255, font=font)
    im.paste(0, (W - 1, 0, W, H)); im.paste(0, (0, H - 1, W, H))
    return [[1 if im.getpixel((x, y)) >= 90 else 0 for x in range(W)] for y in range(H)]

def main():
    font = ImageFont.truetype(FONT, 13)
    cells = {}
    for ch in RAMP:
        g = glyph(ch, font)
        cells[ch] = (sum(map(sum, g)), g)
    chosen = list(RAMP)
    chosen.sort(key=lambda c: cells[c][0])
    words = []
    for ch in chosen:
        g = cells[ch][1]
        for block in range(3):
            v = 0
            for row in range(4):
                bits = 0
                for x in range(W):
                    bits = (bits << 1) | g[block * 4 + row][x]
                v |= bits << (8 * (3 - row))
            words.append("0x%08Xu" % v)
    print("// generated by scripts/wolf/make_ascii_glyphs.py from %s; glyphs, least ink first: %s"
          % (FONT.rsplit("/", 1)[-1], "".join(chosen).replace("\\", "\\\\")))
    print("const uint WP_ASCII[%d] = uint[%d](" % (len(words), len(words)))
    for i in range(0, len(words), 6):
        print("    " + ", ".join(words[i:i + 6]) + ("," if i + 6 < len(words) else ""))
    print(");")
    for ch in chosen:
        print("// '%s' ink %d" % (ch, cells[ch][0]), file=sys.stderr)
        for row in cells[ch][1]:
            print("//   " + "".join("#" if p else "." for p in row), file=sys.stderr)

main()
